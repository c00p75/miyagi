/**
 * Things worth reading once a week rather than once a change.
 *
 * - The weekly report: what was practised, what stuck, what is slipping.
 *   Built from the history log and the review queue. No model involved.
 * - The project file list a model is shown when asked "how does this app
 *   work". Choosing which files to show is most of that feature.
 *
 * No `vscode` import, so both can be tested from the command line.
 */

import { execFile } from "node:child_process";
import path from "node:path";
import { readHistory, summarise } from "../../src/history.js";
import { analyse } from "../../src/insights.js";
import { conceptById, isConceptBin } from "../../src/concepts.js";
import type { DojoRowView, StatusView } from "./engine.js";

/* ------------------------------------------------------------------ *
 * Weekly report
 * ------------------------------------------------------------------ */

const pct = (n: number | null) => (n === null ? "not enough answers yet" : `${Math.round(n * 100)}%`);

export async function weeklyReport(input: {
  status: StatusView;
  dojo: readonly DojoRowView[];
  meterLine: string;
  now?: Date;
}): Promise<string> {
  const now = input.now ?? new Date();
  const since = new Date(now.getTime() - 7 * 86_400_000).toISOString();
  const all = await readHistory();
  const week = all.filter((e) => e.at >= since);
  const stats = summarise(week);
  const insights = analyse(all);

  const met = new Map<string, { title: string; fresh: boolean; files: Set<string> }>();
  for (const e of week) {
    if (e.kind !== "concept" || !e.bin || !isConceptBin(e.bin)) continue;
    const id = e.bin.slice("concept:".length);
    const row = met.get(id) ?? { title: conceptById(id)?.title ?? e.label, fresh: false, files: new Set<string>() };
    if (/^discovered/.test(e.detail)) row.fresh = true;
    const file = / in (.+?)(?: \(panel\))?$/.exec(e.detail)?.[1];
    if (file) row.files.add(file);
    met.set(id, row);
  }

  const slipping = input.dojo.filter((r) => r.seen && r.lapses > 0).sort((a, b) => b.lapses - a.lapses).slice(0, 5);
  const strongest = input.dojo.filter((r) => r.seen && r.box >= 3).slice(0, 5);
  const practise =
    slipping[0] ??
    input.dojo.filter((r) => r.seen).sort((a, b) => a.box - b.box)[0] ??
    null;

  const s = input.status;
  const lines = [
    `# Miyagi: your week`,
    "",
    `_${since.slice(0, 10)} to ${now.toISOString().slice(0, 10)}_`,
    "",
    "## In numbers",
    "",
    `- Practised on **${stats.days}** day${stats.days === 1 ? "" : "s"} this week.`,
    `- Answered **${stats.quizzes}** question${stats.quizzes === 1 ? "" : "s"}, ${stats.quizzesCorrect} correctly.`,
    `- Earned **${stats.xp} XP**. You are level ${s.level} (${s.rank}) with ${s.xp} XP in total.`,
    `- **${s.discovered} of ${s.concepts}** ideas found so far; **${s.dueQuestions}** question${s.dueQuestions === 1 ? " is" : "s are"} due now.`,
    "",
    "## What you met in your code",
    "",
    met.size
      ? [...met.values()]
          .map((m) => `- ${m.fresh ? "**New:** " : ""}${m.title}${m.files.size ? ` (${[...m.files].slice(0, 3).join(", ")})` : ""}`)
          .join("\n")
      : "_No ideas were carded this week. Either your assistant was quiet, or what it wrote used ideas you already hold._",
    "",
    "## Is it sticking",
    "",
    `- First-time answers: ${pct(insights.freshAccuracy)}`,
    `- Answers after a gap (the number that matters): ${pct(insights.reviewAccuracy)}`,
    "",
    insights.verdict,
    "",
    "## Slipping",
    "",
    slipping.length
      ? slipping.map((r) => `- ${r.emoji} ${r.title}: missed ${r.lapses} time${r.lapses === 1 ? "" : "s"}, now ${r.belt} belt`).join("\n")
      : "_Nothing you have learned has been missed in review._",
    "",
    "## Holding firm",
    "",
    strongest.length
      ? strongest.map((r) => `- ${r.emoji} ${r.title}: ${r.belt} belt`).join("\n")
      : "_No idea has reached green belt yet. That takes answering it correctly after 1, 3 and 7 days._",
    "",
    "## One thing to practise",
    "",
    practise
      ? `**${practise.emoji} ${practise.title}.** Open it in the Dojo tab, press "Explain it yourself first", and see how much of it you can say without help.`
      : "_Build something. Ideas unlock when your assistant writes code that uses them._",
    "",
    "---",
    `_${input.meterLine} Generated by Miyagi from \`~/.miyagi/history.jsonl\`. Nothing in this report left your machine._`,
    "",
  ];
  return lines.join("\n");
}

/* ------------------------------------------------------------------ *
 * Project files worth showing
 * ------------------------------------------------------------------ */

function git(cwd: string, args: string[]): Promise<string | null> {
  return new Promise((resolve) => {
    execFile("git", args, { cwd, maxBuffer: 16 * 1024 * 1024, timeout: 15_000, windowsHide: true }, (err, stdout) =>
      resolve(err ? null : String(stdout)),
    );
  });
}

const NOISE =
  /(^|\/)(node_modules|dist|build|out|\.next|vendor|coverage|__pycache__|\.venv|target|\.git)\/|\.(png|jpe?g|gif|svg|ico|webp|woff2?|ttf|mp[34]|pdf|lock|map|min\.(js|css))$|(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml)$/i;

export async function trackedFiles(root: string): Promise<string[]> {
  const out = await git(root, ["ls-files"]);
  return (out ?? "")
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => l && !NOISE.test(l));
}

/** How much a file's name suggests it explains the project. Higher is shown first. */
export function fileInterest(file: string): number {
  const name = path.basename(file).toLowerCase();
  const depth = file.split("/").length - 1;
  let score = 0;
  if (/^readme(\.|$)/.test(name)) score += 100;
  if (/^(package\.json|pyproject\.toml|requirements\.txt|go\.mod|cargo\.toml|pom\.xml|build\.gradle(\.kts)?|composer\.json|gemfile)$/.test(name)) score += 90;
  if (/^(schema\.prisma|schema\.(sql|ts|js)|models\.py|docker-compose\.ya?ml|dockerfile)$/.test(name)) score += 70;
  if (/^(main|index|app|server|cli|manage|routes?|router|urls|layout|page|middleware)\.[a-z]+$/.test(name)) score += 60;
  if (/(route|router|controller|handler|api|service|model|schema|store|auth|config)/.test(file.toLowerCase())) score += 20;
  if (/(test|spec|mock|fixture|example|stories)/.test(file.toLowerCase())) score -= 50;
  return score - depth * 6;
}

/**
 * The file list a model is shown: every folder represented, the most telling
 * files first, capped so a large repository does not become a large bill.
 */
export function chooseFiles(files: readonly string[], options: { tree: number; heads: number }): { tree: string[]; heads: string[] } {
  const ranked = [...files].sort((a, b) => fileInterest(b) - fileInterest(a) || a.localeCompare(b));
  const tree = new Set<string>();
  // One file per folder first, so the shape of the project survives the cap.
  const seenFolders = new Set<string>();
  for (const f of ranked) {
    const folder = path.dirname(f);
    if (seenFolders.has(folder)) continue;
    seenFolders.add(folder);
    tree.add(f);
    if (tree.size >= options.tree) break;
  }
  for (const f of ranked) {
    if (tree.size >= options.tree) break;
    tree.add(f);
  }
  return { tree: [...tree].sort(), heads: ranked.filter((f) => fileInterest(f) > 0).slice(0, options.heads) };
}
